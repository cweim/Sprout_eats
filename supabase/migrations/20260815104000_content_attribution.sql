create or replace function public.admin_content_post_detail(p_content_source_id bigint)
returns jsonb language sql security definer set search_path=public as $$
with o as (select * from public.admin_content_outcomes() where content_source_id=p_content_source_id),
r as (
    select restaurant_key,max(restaurant_name) name,max(city) city,max(cuisine) cuisine,
        sum(new_save_count) new_saves,count(distinct user_id) unique_users,
        count(distinct user_id) filter(where attributed_visit) visits,
        count(distinct user_id) filter(where review_id is not null) reviews,
        round(100.0*count(*) filter(where review_id is not null and sentiment='loved')/nullif(count(*) filter(where review_id is not null),0),1) loved_rate
    from o group by restaurant_key
), metrics as (
    select sum(new_save_count) new_saves,sum(rediscovery_count) rediscoveries,
        count(distinct user_id) unique_users,count(distinct restaurant_key) restaurant_count,
        count(distinct user_id) filter(where attributed_visit) visits,
        count(distinct user_id) filter(where review_id is not null) reviews,
        round(100.0*count(*) filter(where review_id is not null and sentiment='loved')/nullif(count(*) filter(where review_id is not null),0),1) loved_rate,
        avg(review_score) raw_score,min(first_attributed_at) first_attributed_at,max(last_attributed_at) last_attributed_at from o
)
select jsonb_build_object(
    'id',cs.id,'platform',cs.platform,'canonical_url',cs.canonical_url,'source_account',cs.source_account,
    'title',cs.title,'caption_preview',cs.caption_preview,'hashtags',cs.hashtags,'duration_seconds',cs.duration_seconds,
    'new_saves',m.new_saves,'rediscoveries',m.rediscoveries,'unique_users',m.unique_users,
    'restaurant_count',m.restaurant_count,'visits',m.visits,'reviews',m.reviews,
    'loved_rate',coalesce(m.loved_rate,0),'adjusted_score',case when m.raw_score is null then null else round(((m.reviews*m.raw_score)+(5*6.0))/(m.reviews+5),2) end,
    'first_attributed_at',m.first_attributed_at,'last_attributed_at',m.last_attributed_at,
    'restaurants',coalesce((select jsonb_agg(to_jsonb(r) order by r.new_saves desc) from r),'[]'::jsonb)
)
from public.content_sources cs cross join metrics m where cs.id=p_content_source_id;
